import { CAPTURE } from '../vfs/data/generated.js';

const PCAP = '/var/captures/eth0-morning.pcap';

const LOCAL_IP = '10.20.6.40';
const RESOLVER_IP = '10.20.1.10';
const MONITOR_IP = '10.20.9.40';
const BACKUP_IP = '10.20.9.15';
const ATTACKER_IP = '203.0.113.55';
const EXFIL_IP = '198.51.100.60';

// --- reading the capture the same way the engine does ------------------------

interface Packet {
  seconds: number;
  proto: 'tcp' | 'udp' | 'icmp';
  src: string;
  sport: number;
  dst: string;
  dport: number;
  flags: string;
  len: number;
  info: string;
}

function toSeconds(stamp: string): number {
  const [hours, minutes, rest] = stamp.split(':');
  return Number(hours) * 3600 + Number(minutes) * 60 + Number(rest);
}

const PACKETS: Packet[] = CAPTURE.split('\n')
  .filter((line) => line.trim() !== '')
  .map((line) => {
    const field = line.split('|');
    return {
      seconds: toSeconds(field[0]!),
      proto: field[1] as Packet['proto'],
      src: field[2]!,
      sport: Number(field[3]),
      dst: field[4]!,
      dport: Number(field[5]),
      flags: field[6]!,
      len: Number(field[9]),
      info: field[10] ?? '',
    };
  });

/** RFC 1918 and loopback. Everything else in this capture is off-site. */
const isInternal = (address: string) => address.startsWith('10.') || address.startsWith('127.');

const count = (predicate: (packet: Packet) => boolean) => PACKETS.filter(predicate).length;

const TOTAL = PACKETS.length;
const TCP_TOTAL = count((p) => p.proto === 'tcp');
const UDP_TOTAL = count((p) => p.proto === 'udp');
const ICMP_TOTAL = count((p) => p.proto === 'icmp');

/** A lone SYN: a connection attempt, answered or not. */
const SYN_TOTAL = count((p) => p.flags === 'S');

const DNS_TOTAL = count((p) => p.proto === 'udp' && (p.sport === 53 || p.dport === 53));
const RESOLVER_TOTAL = count((p) => p.src === RESOLVER_IP || p.dst === RESOLVER_IP);

const EXTERNAL_ADDRESSES = [
  ...new Set(
    PACKETS.flatMap((p) => [p.src, p.dst]).filter((address) => !isInternal(address)),
  ),
].sort();

/** The attacker's password guessing, counted as connection attempts on SSH. */
const BRUTE_FORCE_SYNS = count(
  (p) => p.src === ATTACKER_IP && p.dport === 22 && p.flags === 'S',
);

const ATTACKER_TOTAL = count((p) => p.src === ATTACKER_IP || p.dst === ATTACKER_IP);

/**
 * The command-and-control beacon, and the interval it keeps.
 *
 * Derived rather than stated: the exercise that asks for the interval is only
 * fair if the interval is whatever the generator actually produced.
 */
const C2_SYNS = PACKETS.filter(
  (p) => p.dst === ATTACKER_IP && p.dport === 443 && p.flags === 'S',
);
const C2_COUNT = C2_SYNS.length;
const C2_INTERVAL = Math.round(C2_SYNS[1]!.seconds - C2_SYNS[0]!.seconds);

/** The decoy beacon: monitoring, internal, and faster than the real one. */
const MONITOR_SYNS = PACKETS.filter(
  (p) => p.src === MONITOR_IP && p.dport === 9100 && p.flags === 'S',
);
const MONITOR_INTERVAL = Math.round(MONITOR_SYNS[1]!.seconds - MONITOR_SYNS[0]!.seconds);

/** Everything to or from the exfiltration destination. */
const EXFIL_TOTAL = count((p) => p.src === EXFIL_IP || p.dst === EXFIL_IP);
const EXFIL_OUTBOUND = count((p) => p.src === LOCAL_IP && p.dst === EXFIL_IP);
const EXFIL_BYTES_OUT = PACKETS.filter((p) => p.src === LOCAL_IP && p.dst === EXFIL_IP).reduce(
  (total, p) => total + p.len,
  0,
);

/**
 * The SSH session that succeeded, found as the attacker's busiest source port.
 *
 * Every failed guess opens a connection and closes it again in a handful of
 * packets. Exactly one of them carries hundreds, which is the difference between
 * a rejected password and a shell.
 */
const attackerSshPorts = new Map<number, Packet[]>();
for (const packet of PACKETS) {
  if (packet.src !== ATTACKER_IP && packet.dst !== ATTACKER_IP) continue;
  if (packet.sport !== 22 && packet.dport !== 22) continue;
  const port = packet.src === ATTACKER_IP ? packet.sport : packet.dport;
  attackerSshPorts.set(port, [...(attackerSshPorts.get(port) ?? []), packet]);
}
const LIVE_SESSION = [...attackerSshPorts.values()].sort((a, b) => b.length - a.length)[0]!;
const LIVE_SESSION_PORT = LIVE_SESSION[0]!.src === ATTACKER_IP ? LIVE_SESSION[0]!.sport : LIVE_SESSION[0]!.dport;
const LIVE_SESSION_PACKETS = LIVE_SESSION.length;
const LIVE_SESSION_MINUTES = Math.round(
  (LIVE_SESSION.at(-1)!.seconds - LIVE_SESSION[0]!.seconds) / 60,
);

/** Ports an outside address tried to open. The scanner's shopping list. */
const SCANNED_PORTS = [
  ...new Set(
    PACKETS.filter((p) => !isInternal(p.src) && p.dst === LOCAL_IP && p.flags === 'S').map(
      (p) => p.dport,
    ),
  ),
].sort((a, b) => a - b);

