const outHas = (text: string, hint?: string): Check => ({
  type: 'output-contains',
  text,
  hint: hint ?? `The output should include "${text}".`,
});

const outLacks = (text: string, hint: string): Check => ({
  type: 'output-excludes',
  text,
  hint,
});

const drill = (
  id: string,
  prompt: string,
  teach: PracticeTeach,
  solution: string,
  checks: Check[],
): PracticeItem => ({ id, prompt, teach, solution, checks });

