/**
 * Packet analysis for the Network Analyst: modules 4.6 to 4.9, 20 exercises.
 *
 * WHY THIS EXISTS SEPARATELY FROM networking.ts
 *
 * Everything in modules 4.1 to 4.5 asks the host what it is doing: `ss`, `ip`,
 * `dig`. All of it is the machine's own account of itself, and all of it stops
 * being trustworthy the moment somebody has root on that machine. The wire does
 * not lie in the same way, and reading it is a different skill with a different
 * tool, so it gets its own file rather than four more modules appended to a
 * file about sockets.
 *
 * WHY tcpdump AND NOT WIRESHARK
 *
 * Wireshark is a GUI and cannot be simulated honestly here. What it teaches --
 * capture filter versus display filter, the layers, the handshake, following one
 * conversation, spotting a beacon -- is the same material, and tcpdump is where
 * most analysts meet it first anyway. A student who finishes this module can sit
 * in front of Wireshark and know what they are looking at.
 *
 * ANSWERS
 *
 * Every count below is computed from the generated capture, never typed in. The
 * capture is regenerated by scripts/generate-world.ts, and an exercise asserting
 * a number somebody once observed would silently rot the first time it changes.
 */

